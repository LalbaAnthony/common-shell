#!/bin/bash

set -euo pipefail

REPO="LalbaAnthony/common-shell"
BRANCH="main"

SRC_URL="https://raw.githubusercontent.com/${REPO}/${BRANCH}/src/bash"
MANIFEST_URL="${SRC_URL}/manifest.txt"
EXTRA_FILE="$HOME/.bashrc_extra"

BASHRC_FILE="$HOME/.bashrc"
BASHRC_HOOK='[ -f ~/.bashrc_extra ] && . ~/.bashrc_extra'

# Must stay identical to uninstall.sh, which removes the unit by these paths.
UNIT_NAME="common-shell-cshall.service"
UNIT_DIR="${XDG_CONFIG_HOME:-$HOME/.config}/systemd/user"
UNIT_FILE="$UNIT_DIR/$UNIT_NAME"

# Set while the concatenation is in flight, cleared once it lands.
TMP_FILE=""

cleanup() {
    if [ -n "$TMP_FILE" ]; then
        rm -f "$TMP_FILE"
    fi
}
trap cleanup EXIT

download_extra() {
    echo "Fetching manifest from $MANIFEST_URL..."
    local manifest
    manifest="$(curl -fsSL "$MANIFEST_URL")"

    # Built next to the target so the final mv is a rename on the same
    # filesystem, and so a failed part download can never leave a truncated
    # ~/.bashrc_extra behind for ~/.bashrc to source.
    TMP_FILE="$(mktemp "${EXTRA_FILE}.XXXXXX")"

    {
        echo "# Generated by common-shell from ${REPO}@${BRANCH}."
        echo "# Do not edit: change src/bash/*.sh in the repo, then re-run 'cshupd'."
        echo ""
    } > "$TMP_FILE"

    local part count=0
    while IFS= read -r part || [ -n "$part" ]; do
        # Strip comments, then all whitespace - which also absorbs the CR of a
        # CRLF manifest. Part names are filenames and carry no spaces.
        part="${part%%#*}"
        part="$(printf '%s' "$part" | tr -d '[:space:]')"
        [ -n "$part" ] || continue

        echo "  + ${part}"
        curl -fsSL "${SRC_URL}/${part}" >> "$TMP_FILE"

        # Separator, and a safety net for a part with no trailing newline.
        printf '\n' >> "$TMP_FILE"

        count=$((count + 1))
    done <<< "$manifest"

    if [ "$count" -eq 0 ]; then
        echo "Manifest listed no files, aborting." >&2
        return 1
    fi

    echo "Writing $count part(s) to $EXTRA_FILE..."
    chmod 644 "$TMP_FILE"   # mktemp creates 0600
    mv -f "$TMP_FILE" "$EXTRA_FILE"
    TMP_FILE=""
}

register_in_bashrc() {
    if grep -qxF "$BASHRC_HOOK" "$BASHRC_FILE"; then
        echo "Hook already present in $BASHRC_FILE, skipping."
    else
        echo "Registering hook in $BASHRC_FILE..."
        echo "" >> "$BASHRC_FILE"
        echo "$BASHRC_HOOK" >> "$BASHRC_FILE"
    fi
}

# False on macOS, Git Bash, WSL without systemd, containers, and `su` shells
# that have no XDG_RUNTIME_DIR to reach the user manager through.
has_user_systemd() {
    command -v systemctl > /dev/null 2>&1 && systemctl --user show-environment > /dev/null 2>&1
}

register_login_service() {
    if ! has_user_systemd; then
        echo "No reachable systemd user manager, skipping login service."
        return
    fi

    echo "Installing $UNIT_FILE..."
    mkdir -p "$UNIT_DIR"

    # Runs detached from any terminal. Type=simple, not oneshot: logind holds
    # the login until the user manager reaches default.target, so a oneshot
    # would block every first login on the network. Non-interactive bash does
    # not read ~/.bashrc, hence the explicit source. cshall is an alias chain,
    # and non-interactive bash expands no aliases: expand_aliases enables it,
    # and eval defers the lookup to after the source - an alias used on the
    # same line that defines it is never expanded. Output goes to
    # `journalctl --user -u common-shell-cshall`.
    cat > "$UNIT_FILE" << 'EOF'
[Unit]
Description=common-shell: run cshall at login
ConditionPathExists=%h/.bashrc_extra

[Service]
Type=simple
ExecStart=/bin/bash -O expand_aliases -c '. "%h/.bashrc_extra"; eval cshall'

[Install]
WantedBy=default.target
EOF

    systemctl --user daemon-reload
    systemctl --user enable "$UNIT_NAME"
}

reload_shell() {
    echo "Reloading shell..."
    # source may not propagate to the parent shell when run via curl | bash
    # shellcheck disable=SC1090
    source "$BASHRC_FILE" || true
}

main() {
    download_extra
    register_in_bashrc
    register_login_service
    reload_shell
    echo "Bash extra installed successfully!"
}

main
